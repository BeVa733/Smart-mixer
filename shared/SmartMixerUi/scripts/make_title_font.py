#!/usr/bin/env python3
"""Generate mixer_font_title (DejaVu Sans Bold 24 px) as an LVGL fmt_txt font.

Same glyph set and layout as mixer_font_16 (ASCII, Cyrillic U+0400-045F, em dash),
4 bpp, uncompressed, no kerning. Rendered with FreeType through Pillow, so it can be
regenerated without lv_font_conv:
    python3 shared/SmartMixerUi/scripts/make_title_font.py [path/to/DejaVuSans-Bold.ttf]
Writes shared/SmartMixerUi/src/mixer_font_title.c. Font license: FONT_LICENSE.txt.
"""
import os
import sys
from PIL import ImageFont

SIZE = 24
NAME = "mixer_font_title"
RANGES = [(0x20, 0x7E), (0x400, 0x45F), (0x2014, 0x2014)]
DEFAULT_TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def glyph(font, ascent, ch):
    advance = font.getlength(ch)
    mask, (ox, oy) = font.getmask2(ch, mode="L")
    w, h = mask.size
    pixels = [[mask.getpixel((x, y)) for x in range(w)] for y in range(h)]
    rows = [y for y in range(h) if any(pixels[y])]
    cols = [x for x in range(w) if any(pixels[y][x] for y in range(h))]
    if not rows or not cols:
        return round(advance * 16), 0, 0, 0, 0, []
    top, bottom, left, right = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    data = [(pixels[y][x] * 15 + 127) // 255 for y in range(top, bottom) for x in range(left, right)]
    box_w, box_h = right - left, bottom - top
    ofs_x = ox + left
    ofs_y = ascent - (oy + bottom)  # bottom of the box above the baseline
    return round(advance * 16), box_w, box_h, ofs_x, ofs_y, data


def main():
    ttf = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_TTF
    font = ImageFont.truetype(ttf, SIZE)
    ascent, descent = font.getmetrics()
    bitmap, dscs = bytearray(), []
    for start, end in RANGES:
        for code in range(start, end + 1):
            adv, bw, bh, ox, oy, data = glyph(font, ascent, chr(code))
            index = len(bitmap)
            for i in range(0, len(data), 2):
                hi = data[i]
                lo = data[i + 1] if i + 1 < len(data) else 0
                bitmap.append((hi << 4) | lo)
            dscs.append((index, adv, bw, bh, ox, oy))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", NAME + ".c")
    with open(out, "w") as f:
        f.write(f"/* {NAME}: DejaVu Sans Bold {SIZE} px, 4 bpp, ranges 0x20-0x7E,0x400-0x45F,0x2014.\n"
                f" * Generated by scripts/make_title_font.py; do not edit by hand. */\n")
        f.write("#ifdef LV_LVGL_H_INCLUDE_SIMPLE\n#include \"lvgl.h\"\n#else\n#include \"lvgl/lvgl.h\"\n#endif\n\n")
        f.write("static const uint8_t glyph_bitmap[] = {\n")
        for i in range(0, len(bitmap), 24):
            f.write("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 24]) + ",\n")
        f.write("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
        f.write("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},\n")
        for index, adv, bw, bh, ox, oy in dscs:
            f.write(f"    {{.bitmap_index = {index}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, "
                    f".ofs_x = {ox}, .ofs_y = {oy}}},\n")
        f.write("};\n\nstatic const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
        glyph_id = 1
        for start, end in RANGES:
            f.write(f"    {{.range_start = {start}, .range_length = {end - start + 1}, .glyph_id_start = {glyph_id},\n"
                    f"     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,"
                    f" .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},\n")
            glyph_id += end - start + 1
        f.write("};\n\n")
        f.write(f"""static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = {len(RANGES)}, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0,
}};

const lv_font_t {NAME} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 2,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
""")


if __name__ == "__main__":
    main()
